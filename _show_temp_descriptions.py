import django, os
os.environ.setdefault('DJANGO_SETTINGS_MODULE', 'djangoProject1.settings')
django.setup()

from params.exd_models import TemperatureClass

classes = TemperatureClass.objects.filter(is_active=True).order_by('sorting_order')

descriptions = {
    'T1': 'Максимальная температура поверхности 450°C. Подходит для газов с температурой воспламенения выше 450°C (водород, метан, пропан). Наименее строгий класс.',
    'T2': 'Максимальная температура поверхности 300°C. Для газов с температурой воспламенения выше 300°C (этилен, бутан, этанол).',
    'T3': 'Максимальная температура поверхности 200°C. Для газов с температурой воспламенения выше 200°C (бензин, дизельное топливо).',
    'T4': 'Максимальная температура поверхности 135°C. Для газов с температурой воспламенения выше 135°C (сероуглерод, диэтиловый эфир). Наиболее распространённый класс для общепромышленного оборудования.',
    'T5': 'Максимальная температура поверхности 100°C. Для газов с температурой воспламенения выше 100°C. Повышенные требования к теплоотводу.',
    'T6': 'Максимальная температура поверхности 85°C. Для газов с самой низкой температурой воспламенения (сероуглерод). Наиболее строгий класс.',
}

print("=" * 70)
print(f"{'ID':>3} | {'Класс':<5} | {'T макс':>5} | {'Восплам.':>7} | Текущее описание")
print("-" * 70)

for t in classes:
    code = t.temperature_class
    suggested = descriptions.get(code, '')
    current = t.description or '(пусто)'
    print(f"{t.id:>3} | {code:<5} | {t.max_surface_temp:>5}°C | {t.gas_ignition_temp or '—':>7} | {current[:50]}")
    if suggested:
        print(f"     → ПРЕДЛАГАЕМОЕ: {suggested}")
    print()

